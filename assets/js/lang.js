  var root = document.documentElement;
  var ARABIC = /[؀-ۿ]/;
  function apply(lang) {
    root.setAttribute("data-lang", lang);
    root.setAttribute("lang", lang);
    root.setAttribute("dir", lang === "ar" ? "rtl" : "ltr");
    var table = text[lang] || {};
    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      var v = table[el.getAttribute("data-i18n")];
      if (v == null) return;
      el.textContent = v;
      el.setAttribute("lang", ARABIC.test(v) ? "ar" : "en");
    });
    document.querySelectorAll("[data-i18n-aria]").forEach(function (el) {
      var v = table[el.getAttribute("data-i18n-aria")];
      if (v != null) el.setAttribute("aria-label", v);
    });
    document.querySelectorAll("[data-i18n-alt]").forEach(function (el) {
      var v = table[el.getAttribute("data-i18n-alt")];
      if (v != null) el.setAttribute("alt", v);
    });
    var page = root.getAttribute("data-page");
    if (page && table["meta." + page + ".title"] != null) {
      document.title = table["meta." + page + ".title"];
      var m = document.querySelector('meta[name="description"]');
      if (m && table["meta." + page + ".desc"] != null)
        m.setAttribute("content", table["meta." + page + ".desc"]);
    }
    try { localStorage.setItem("aa-lang", lang); } catch (e) {}
  }
  var toggle = document.querySelector("[data-lang-toggle]");
  function themeLabel() {
    var btn = document.querySelector("[data-theme-toggle]");
    if (!btn) return;
    var lang = root.getAttribute("data-lang") === "en" ? "en" : "ar";
    var light = root.getAttribute("data-theme") === "light";
    var key = light ? "themeDark" : "themeLight";
    var aria = light ? "themeAriaDark" : "themeAriaLight";
    btn.setAttribute("aria-label", (text[lang] && text[lang][aria]) || "");
    var span = btn.querySelector(".theme__text");
    if (span && text[lang] && text[lang][key] != null) {
      span.textContent = text[lang][key];
      span.setAttribute("lang", lang);
    }
  }
  function langLabel() {
    if (!toggle) return;
    var lang = root.getAttribute("data-lang") === "en" ? "en" : "ar";
    var aria = lang === "en" ? "langAriaOther" : "langAria";
    toggle.setAttribute("aria-label", (text[lang] && text[lang][aria]) || "");
  }
